"""Publish aggregate-only Phase 5A tables and figure; never read raw scene geometry."""

import argparse
import json
from pathlib import Path
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--inputs", default="data/outputs/phase5")
    p.add_argument("--output", default="docs")
    a = p.parse_args()
    root, out = Path(a.inputs), Path(a.output)
    out.mkdir(parents=True, exist_ok=True)
    sources = dict(
        scans="scan_audit.json",
        windows="window_audit.json",
        synthetic="synthetic_release/metrics.json",
        real="release_real_metrics.json",
    )
    data = {
        key: json.loads((root / value).read_text()) for key, value in sources.items()
    }
    data["metadata"] = dict(
        date="2026-11-11",
        base_commit="9068088542067fc117535279b412fbf2f808fdf6",
        real_baseline_commit="ecfaae38984a598a9839b17582c31be42532972d",
        real_profile="configs/stable_lidar.yaml",
        caution="Development data; annotations not human-verified. No held-out or live validation. Availability includes stale geometry; it is not fresh motion recall.",
    )
    (out / "STABLE_LIDAR_METRICS.json").write_text(
        json.dumps(data, indent=2, allow_nan=False) + "\n"
    )

    def f(v):
        return "—" if v is None else f"{v:.3f}"

    rows = [
        "# Phase 5A aggregate results",
        "",
        "Generated by `scripts/report_stable_scene.py`. Read STABLE_LIDAR_EXPERIMENTS.md for definitions and limitations.",
        "",
        "## Real geometry and motion",
        "",
        "Each pair is original → Phase 5A. Coverage is observed-only; availability also allows held stale boxes. Lower jitter conditional on fewer matches is not proof of overall improvement.",
        "",
        "| Recording/object | Fresh coverage | Availability | Static jitter m | False MOVING | Moving recall | Velocity error m/s |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in data["real"].items():
        for key, v in r["stable"]["objects"].items():
            b = r["baseline"]["objects"][key]

            def pair(metric):
                return f(b[metric]) + " → " + f(v[metric])

            available = (
                f(r["baseline_availability"]["objects"][key]["coverage"])
                + " → "
                + f(r["stable_availability"]["objects"][key]["coverage"])
            )
            rows.append(
                f"| {name}/{key} | {pair('coverage')} | {available} | {pair('centroid_jitter_xy_m')} | {pair('false_moving_rate')} | {pair('moving_recall')} | {pair('velocity_error_mps')} |"
            )
    rows += [
        "",
        "## Proposal failure and persistence",
        "",
        "Rates use each object's scorable frames; longest run breaks at gaps >0.2 s and is divided by all scorable frames. Duplication counts multiple estimates in the gate, not verified false physical objects.",
        "",
        "| Recording/object | Background merge | No cluster | Duplicate frames | Longest fresh fraction | Longest available fraction |",
        "|---|---|---|---|---|---|",
    ]
    for name, r in data["real"].items():
        for key, v in r["stable"]["objects"].items():
            b = r["baseline"]["objects"][key]
            rates = [
                f(b["proposal_states"].get(k, 0) / b["counts"]["detectable"])
                + " → "
                + f(v["proposal_states"].get(k, 0) / v["counts"]["detectable"])
                for k in ["merged_background", "no_cluster"]
            ]

            def pair(k):
                return f(b[k]) + " → " + f(v[k])

            avail = (
                f(
                    r["baseline_availability"]["objects"][key][
                        "longest_observed_fraction"
                    ]
                )
                + " → "
                + f(
                    r["stable_availability"]["objects"][key][
                        "longest_observed_fraction"
                    ]
                )
            )
            dup = (
                str(b["counts"]["duplicate_frames"])
                + " → "
                + str(v["counts"]["duplicate_frames"])
            )
            rows.append(
                f"| {name}/{key} | {rates[0]} | {rates[1]} | {dup} | {pair('longest_observed_fraction')} | {avail} |"
            )
    rows += [
        "",
        "## Runtime and staleness",
        "",
        "Runtime is pipeline computation, excluding serialization/I/O; no comparable original end-to-end timing is available in the cached real baseline.",
        "",
        "| Recording | Mean ms | p95 ms | Stale/all boxes original → new |",
        "|---|---|---|---|",
    ]
    for name, r in data["real"].items():
        rows.append(
            f"| {name} | {f(r['runtime']['mean'])} | {f(r['runtime']['p95'])} | {f(r['baseline']['stale_fraction'])} → {f(r['stable']['stale_fraction'])} |"
        )
    rows += [
        "",
        "## Synthetic horizons",
        "",
        "Original uses existing processor/tracker with 0.3 s odom accumulation. All supported births are counted, including tentative baseline tracks. Latencies vary with host load.",
        "",
        "| Scenario | Window s | Coverage | Static jitter m | Moving recall | Dimension error m | Motion delay s | Mean / p95 ms |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, variants in data["synthetic"].items():
        for window, r in variants.items():
            delay = (
                ", ".join(f(e["moving_delay_s"]) for e in r["transition_events"]) or "—"
            )
            rows.append(
                f"| {name} | {window} | {f(r['coverage'])} | {f(r['stationary_jitter_xy_m'])} | {f(r['moving_recall'])} | {f(r['dimension_error_mean_m'])} | {delay} | {f(r['processing_ms']['mean'])} / {f(r['processing_ms']['p95'])} |"
            )
    (out / "STABLE_LIDAR_RESULTS.md").write_text("\n".join(rows) + "\n")
    windows = ["0.1", "0.3", "0.6", "1.0"]
    x = [float(w) for w in windows]
    fig, axes = plt.subplots(1, 2, figsize=(10, 4), layout="constrained")
    for name, result in data["windows"].items():
        axes[0].plot(
            x,
            [result[w]["static_roi_centroid_jitter_m"] for w in windows],
            marker="o",
            label=name,
        )
    axes[0].set(
        title="Real static ROI: annotation-only diagnostic",
        xlabel="Accumulation window (s)",
        ylabel="Centroid jitter (m)",
    )
    axes[0].legend(fontsize=8)
    for scenario in ["start_move", "near_furniture"]:
        axes[1].plot(
            x,
            [data["synthetic"][scenario][w]["moving_recall"] for w in windows],
            marker="o",
            label=scenario,
        )
    axes[1].set(
        title="Synthetic motion recall: longer is not always better",
        xlabel="Accumulation window (s)",
        ylabel="Observed MOVING recall",
        ylim=(0, 1),
    )
    axes[1].legend(fontsize=8)
    for ax in axes:
        ax.grid(alpha=0.25)
    fig.savefig(out / "STABLE_LIDAR_TRADEOFFS.png", dpi=160)
    plt.close(fig)


if __name__ == "__main__":
    main()
